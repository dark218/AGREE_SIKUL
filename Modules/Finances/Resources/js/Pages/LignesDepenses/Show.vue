                                <i class="fa fa-chevron-up"></i>
                            </button>
                        </div>
                        <div class="dash-payment-body" :class="{ collapsed: isCollapsed }">
                            <LignesDepensesForm :form="form" mode="show" />
                            <div class="row mt-3">
                                <div class="col">
                                    <div class="text-end">
