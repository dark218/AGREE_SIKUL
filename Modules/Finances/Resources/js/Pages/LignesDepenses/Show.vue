import { ref } from 'vue';
import { Link, useForm, usePage } from '@inertiajs/vue3';
import { useI18n } from 'vue-i18n';
import DashboardLayout from '@/Layouts/DashboardLayout.vue';
import LignesDepensesForm from './LignesDepensesForm.vue';

defineOptions({ layout: DashboardLayout });

const { t } = useI18n();
const page = usePage();
const isCollapsed = ref(false);

const toggleCollapse = () => {
    isCollapsed.value = !isCollapsed.value;
};

const props = defineProps({
    title: String,
    ligne_depense: Object,
});

const form = useForm({
    code: page.props.ligne_depense?.code || '',
    libelle: page.props.ligne_depense?.libelle || '',
    compte_comptable: page.props.ligne_depense?.compte_comptable || '',
